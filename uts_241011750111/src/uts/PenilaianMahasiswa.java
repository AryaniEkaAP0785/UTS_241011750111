    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txtNim.getText().trim().isEmpty() || txtNama.getText().trim().isEmpty()
                || (!rbLaki.isSelected() && !rbPerempuan.isSelected())) {
            JOptionPane.showMessageDialog(this,
                "NIM, Nama, dan Jenis Kelamin harus diisi!",
                "Validasi", JOptionPane.WARNING_MESSAGE);
            return;
        }

        btnProsesActionPerformed(null); // hitung ulang supaya hasil tidak basi
        if (txtGrade.getText().isEmpty()) {
            return; // Proses gagal validasi, pesan sudah tampil
        }

        String jk = rbLaki.isSelected() ? "LAKI-LAKI" : "PEREMPUAN";
        txtLog.append(txtNim.getText().trim()
            + " | " + txtNama.getText().trim()
            + " | " + jk
            + " | Matkul : " + cmbMatkul.getSelectedItem()
            + " | SKS : " + txtSks.getText()
            + " | Absensi : " + txtPresensi.getText().trim()
            + " | Tugas : " + txtTugas.getText().trim()
            + " | UTS : " + txtUts.getText().trim()
            + " | UAS : " + txtUas.getText().trim()
            + " | Nilai Akhir : " + txtNilaiAkhir.getText()
            + " | Grade : " + txtGrade.getText() + "\n");
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        txtNilaiAkhir.setText("");
        txtGrade.setText("");
        try {
            int sks = Integer.parseInt(txtSks.getText().trim());
            int jmlPertemuan = (sks == 3) ? 21 : 14;
            
            int presensi = Integer.parseInt(txtPresensi.getText().trim());
            double tugas = Double.parseDouble(txtTugas.getText().trim());
            double uts = Double.parseDouble(txtUts.getText().trim());
            double uas = Double.parseDouble(txtUas.getText().trim());
            
            if (presensi > jmlPertemuan) {
                JOptionPane.showMessageDialog(this,
                    "Presensi (" + presensi + ") melebihi jumlah pertemuan (" + jmlPertemuan + ")!",
                    "Validasi", JOptionPane.WARNING_MESSAGE);
                return;
            }
            if (presensi < 0 || tugas < 0 || uts < 0 || uas < 0
                    || tugas > 100 || uts > 100 || uas > 100) {
                JOptionPane.showMessageDialog(this,
                    "Nilai tidak boleh negatif, dan Tugas/UTS/UAS maksimal 100!",
                    "Validasi", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            double persenHadir = (double) presensi / jmlPertemuan * 100;
            double nAbsen = persenHadir * 0.1;
            double nTugas = tugas * 0.2;
            double nUts = uts * 0.3;
            double nUas = uas * 0.4;
            double nilaiAkhir = nAbsen + nTugas + nUts + nUas;
            
            String grade;
            if (persenHadir < 50) {
                grade = "E";
            } else if (persenHadir < 75) {
                grade = "D";
            } else if (nilaiAkhir > 80) {
                grade = "A";
            } else if (nilaiAkhir > 60) {
                grade = "B";
            } else if (nilaiAkhir > 40) {
                grade = "C";
            } else {
                grade = "D"; // asumsi: soal tidak mengatur nilai <= 40
            }

            txtNilaiAkhir.setText(String.format(java.util.Locale.US, "%.2f", nilaiAkhir));
            txtGrade.setText(grade);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Presensi, Tugas, UTS, dan UAS harus diisi angka!",
                "Input tidak valid", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnProsesActionPerformed

